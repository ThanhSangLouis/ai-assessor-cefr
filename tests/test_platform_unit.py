# ================================================================= SQL dialects


def test_placeholders_become_postgres_parameters_outside_quoted_text():
    sql = "SELECT * FROM t WHERE a=? AND note='who? 50%' AND b LIKE ?"
    assert to_postgres(sql, True) == (
        "SELECT * FROM t WHERE a=%s AND note='who? 50%%' AND b LIKE %s"
    )
    # No parameters: nothing to bind, so nothing is rewritten.
    assert to_postgres("SELECT '50%' AS x", False) == "SELECT '50%' AS x"


def test_insert_or_ignore_and_begin_immediate_have_postgres_equivalents():
    assert to_postgres("INSERT OR IGNORE INTO t(a) VALUES (?)", True) == (
        "INSERT INTO t(a) VALUES (%s) ON CONFLICT DO NOTHING"
    )
    assert "pg_advisory_xact_lock" in to_postgres("BEGIN IMMEDIATE", False)


def test_table_definitions_keep_the_values_sqlite_would_keep():
    ddl = ddl_to_postgres(
        "CREATE TABLE IF NOT EXISTS e (\n"
        "    id INTEGER PRIMARY KEY AUTOINCREMENT,\n"
        "    amount INTEGER NOT NULL,\n"
        "    score REAL,\n"
        "    PRIMARY KEY (amount)\n)"
    )
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "amount BIGINT NOT NULL" in ddl  # amounts in dong pass two billion
    assert "score DOUBLE PRECISION" in ddl  # REAL is four bytes in PostgreSQL
    assert ddl.rstrip().endswith("rowid BIGINT GENERATED ALWAYS AS IDENTITY\n)")
    assert "rowid" not in ddl_to_postgres("CREATE INDEX IF NOT EXISTS i ON e(amount)")


def test_a_schema_script_splits_into_statements_without_its_comments():
    script = "-- a; comment\nCREATE TABLE a (x TEXT); -- trailing\n\nCREATE INDEX i ON a(x);\n"
    assert split_script(script) == ["CREATE TABLE a (x TEXT)", "CREATE INDEX i ON a(x)"]


def test_a_postgres_row_reads_like_a_sqlite_row():
    row = Row(["account_id", "rowid", "n"], ("a1", 7, 3))
    assert row["account_id"] == "a1" and row[2] == 3
    assert dict(row) == {"account_id": "a1", "n": 3}  # rowid stays out, as in SQLite
    with pytest.raises(IndexError):
        row["missing"]


# ================================================================= the in-process bus


def test_inline_events_reach_every_subscriber_and_one_failure_stops_none():
    bus = InlineBus(InlineJobQueue())
    got = []
    bus.subscribe("consent.changed", "a", lambda m: (_ for _ in ()).throw(RuntimeError("x")))
    bus.subscribe("consent.changed", "b", got.append)
    bus.publish("consent.changed", {"account_id": "u"})
    assert got == [{"account_id": "u"}]


def test_only_background_queues_go_through_the_job_queue():
    ran = []

    class Recording(InlineJobQueue):
        def enqueue(self, func, /, *args, **kwargs):
            ran.append("pool")
            super().enqueue(func, *args, **kwargs)

    bus = InlineBus(Recording())
    bus.consume("speech.score", lambda m: ran.append("score"))
    bus.consume("assessment.scoring", lambda m: ran.append("result"))
    bus.send("speech.score", {})
    bus.send("assessment.scoring", {})
    assert ran == ["pool", "score", "result"]


def test_a_call_nobody_serves_is_a_timeout():
    bus = InlineBus(InlineJobQueue())
    with pytest.raises(BusTimeout):
        bus.call("speech.step", {})
    bus.serve("speech.step", lambda req: {"echo": req["x"]})
    assert bus.call("speech.step", {"x": 1}) == {"echo": 1}


# ================================================================= internal calls


def test_a_refused_internal_call_raises_with_its_status():
    def refusing(method, path, body):
        return 403, {"detail": "internal endpoint"}

    remote = RemoteFacade("identity", refusing)
    with pytest.raises(RemoteError) as e:
        remote.count_role(role="student")
    assert e.value.status == 403
    with pytest.raises(AttributeError):
        remote._private  # noqa: B018 - private names are never forwarded


def test_an_unreachable_service_is_a_503():
    def down(method, path, body):
        raise ConnectionRefusedError("no route")

    with pytest.raises(RemoteError) as e:
        RemoteFacade("learning", down).attempts(account_id="a")
    assert e.value.status == 503


# ================================================================= the gateway


def test_the_account_header_round_trips_and_rejects_garbage():
    account = Account("a1", "SV-001", Role.STUDENT, must_change_password=True, daily_goal_s=300)
    back = decode_account(encode_account(account))
    assert back == account
    assert decode_account("") is None and decode_account("bm90IGpzb24") is None
    assert encode_account(None) == ""


