"""The gateway's routing table and the nginx configuration made from it (D043, D044).

The browser talks to one address. The gateway asks the core service who the
session cookie belongs to (`auth_request` to `/internal/identity/session`),
forwards the answer to the service that owns the path in `X-Aicefr-Account`
together with the gateway's key, and never forwards `/internal/` itself.

Two services answer browsers: core, every API; web, the pages and static
files, and the sidebar's counts, which it gathers from core. The speech
service answers none. The table is here, in Python, so that every route can be
checked against it (`tests/test_services_split.py`) and the nginx file is
generated from it (`tools/gen_gateway.py`), never edited by hand.
"""

from __future__ import annotations

# Longest prefix first wins; nginx does the same with prefix locations.
#
# Every location overwrites X-Forwarded-For with the address the gateway saw,
# never appending to what the client sent: the login rate limit counts by that
# address, and a client must not choose its own.
PREFIXES: dict[str, str] = {
    "/api/v1/me/badges": "web",
    "/api/": "core",
    "/auth/google/": "core",
    "/billing/": "core",
    "/docs": "core",
    "/openapi.json": "core",
    # Every other path is a page or a static file.
    "/": "web",
}
EXACT: dict[str, str] = {}

SERVICES = ("core", "web")
INTERNAL_PREFIX = "/internal/"


def service_for(path: str) -> str | None:
    """Which service answers `path` behind the gateway; None for what it never forwards."""
    if path.startswith(INTERNAL_PREFIX):
        return None
    if path in EXACT:
        return EXACT[path]
    best = max((p for p in PREFIXES if path.startswith(p)), key=len)
    return PREFIXES[best]


# ================================================================= nginx

_HEAD = """\
# Generated by tools/gen_gateway.py from aicefr/platform/gateway.py (D043, D044). Do not edit.
# Rendered by the nginx image's envsubst at start: the gateway token below is
# replaced by the deployment's key; nginx's own $variables are left alone.

# Names are resolved when a request is forwarded, not once at start: a service
# recreated by `docker compose up` comes back on a new address, and an address
# remembered from before may by then belong to another service. 127.0.0.11 is
# the DNS server Docker gives every container.
resolver 127.0.0.11 valid=10s ipv6=off;

server {{
    listen 80;
    server_tokens off;
    # A recording up to 25 MiB, with room for the form around it.
    client_max_body_size 30m;
    # A lesson step waits for the speech service; the slowest answers take a minute.
    proxy_read_timeout 180s;

    # Who is calling, asked of the core service for every request below.
    location = /_session {{
        internal;
        set $aicefr_core core:8000;
        proxy_pass http://$aicefr_core/internal/identity/session;
        proxy_pass_request_body off;
        proxy_set_header Content-Length "";
        proxy_set_header X-Aicefr-Gateway "${{AICEFR_GATEWAY_TOKEN}}";
        proxy_set_header X-Aicefr-Internal "";
    }}

    # Service-to-service only: never from outside.
    location /internal/ {{
        return 404;
    }}
{locations}
}}
"""

_LOCATION = """
    location {modifier}{path} {{
        auth_request /_session;
        auth_request_set $aicefr_account $upstream_http_x_aicefr_account;
        proxy_set_header X-Aicefr-Account $aicefr_account;
        proxy_set_header X-Aicefr-Gateway "${{AICEFR_GATEWAY_TOKEN}}";
        # The internal key is the services' own; a browser's copy is dropped.
        proxy_set_header X-Aicefr-Internal "";
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        set $aicefr_upstream {service}:8000;
        proxy_pass http://$aicefr_upstream;
    }}
"""


def nginx_config() -> str:
    locations = "".join(
        _LOCATION.format(modifier="= ", path=path, service=service)
        for path, service in EXACT.items()
    ) + "".join(
        _LOCATION.format(modifier="", path=path, service=service)
        for path, service in sorted(PREFIXES.items(), key=lambda kv: -len(kv[0]))
    )
    return _HEAD.format(locations=locations)
