"""Where every repository keeps its rows: one SQLite file, or one schema of PostgreSQL.

A repository names its store with one string. A path (`aicefr.db`) is a SQLite
file: the default, what the tests use, and what a single machine needs. A URL
(`postgresql://user:pass@db:5432/aicefr?schema=assessment`) is one schema of a
PostgreSQL database: what the services use, each in a schema of its own and
none reading another's (D043).

The repositories are written once, in the SQL both dialects share. What
differs is translated here, and only that:

* `?` placeholders become `%s`, and a literal `%` is doubled;
* `INSERT OR IGNORE` becomes `INSERT ... ON CONFLICT DO NOTHING`;
* `BEGIN IMMEDIATE` -- "take the write lock now" -- becomes an advisory lock
  held to the end of the transaction, which serialises writers the same way;
* in table definitions, `INTEGER` becomes `BIGINT` (amounts in dong pass two
  billion), `REAL` becomes `DOUBLE PRECISION` (PostgreSQL's `REAL` is four
  bytes and would store 3.4 as 3.4000001), `INTEGER PRIMARY KEY AUTOINCREMENT`
  becomes an identity column, and every table gets the `rowid` SQLite gives
  it implicitly, since a few queries break ties by insertion order;
* rows read like `sqlite3.Row`, by position and by name, and `rowid` stays out
  of `keys()` as it does in SQLite;
* `True` is written as 1, as SQLite stores it, and a sum read as `numeric`
  comes back as an int or a float rather than a `Decimal`.

PostgreSQL needs `psycopg` (the `services` extra), imported only when a URL is
used, so a SQLite install does not need it.
"""

from __future__ import annotations

import re
import sqlite3
import threading
from collections.abc import Iterable, Iterator, Sequence
from contextlib import contextmanager
from datetime import UTC, datetime
from decimal import Decimal
from pathlib import Path
from urllib.parse import parse_qsl, quote, urlencode, urlsplit, urlunsplit

POSTGRES_SCHEMES = ("postgresql://", "postgres://")


def now_iso() -> str:
    """The time rows are stamped with: UTC, to the second."""
    return datetime.now(UTC).isoformat(timespec="seconds")


def is_postgres(target: str | Path) -> bool:
    return str(target).startswith(POSTGRES_SCHEMES)


# ================================================================= translation


def _scan(sql: str) -> Iterator[tuple[str, bool]]:
    """The statement in pieces, each flagged as inside a quoted literal or not."""
    piece, quoted = [], False
    for ch in sql:
        if ch == "'":
            if piece:
                yield "".join(piece), quoted
                piece = []
            yield ch, True
            quoted = not quoted
            continue
        piece.append(ch)
    if piece:
        yield "".join(piece), quoted


_INSERT_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", re.I)
_BEGIN_IMMEDIATE = re.compile(r"^\s*BEGIN\s+IMMEDIATE\s*;?\s*$", re.I)
ADVISORY_LOCK = "SELECT pg_advisory_xact_lock(hashtext(current_schema()))"


def to_postgres(sql: str, has_params: bool) -> str:
    """One data statement in the SQLite dialect, written for PostgreSQL."""
    if _BEGIN_IMMEDIATE.match(sql):
        return ADVISORY_LOCK
    ignore = bool(_INSERT_OR_IGNORE.match(sql))
    if ignore:
        sql = _INSERT_OR_IGNORE.sub("INSERT INTO", sql, count=1)
    if has_params:
        out = []
        for piece, quoted in _scan(sql):
            piece = piece.replace("%", "%%")
            out.append(piece if quoted else piece.replace("?", "%s"))
        sql = "".join(out)
    if ignore:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


_TYPES = (
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I),
     "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b", re.I), "BIGINT"),
    (re.compile(r"\bREAL\b", re.I), "DOUBLE PRECISION"),
    (re.compile(r"\bBLOB\b", re.I), "BYTEA"),
)  # fmt: skip
_CREATE_TABLE = re.compile(r"^\s*CREATE\s+TABLE\b", re.I)


def ddl_to_postgres(stmt: str) -> str:
    """One schema statement in the SQLite dialect, written for PostgreSQL."""
    for pattern, replacement in _TYPES:
        stmt = pattern.sub(replacement, stmt)
    if _CREATE_TABLE.match(stmt) and not re.search(r"\browid\b", stmt, re.I):
        close = stmt.rstrip().rfind(")")
        stmt = stmt[:close] + ",\n    rowid BIGINT GENERATED ALWAYS AS IDENTITY\n" + stmt[close:]
    return stmt


def split_script(script: str) -> list[str]:
    """The statements of a schema script. Comments go; no statement here holds a `;`."""
    lines = [line.split("--", 1)[0] for line in script.splitlines()]
    return [s.strip() for s in "\n".join(lines).split(";") if s.strip()]


# ================================================================= PostgreSQL


class Row(tuple):
    """A PostgreSQL row read like `sqlite3.Row`: by position, by name, and with `keys()`."""

    def __new__(cls, names: Sequence[str], values: Sequence) -> Row:
        row = super().__new__(cls, values)
        row._names = names
        return row

    def keys(self) -> list[str]:
        return [n for n in self._names if n != "rowid"]

    def __getitem__(self, key):  # type: ignore[override]
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._names.index(key))
            except ValueError:
                raise IndexError(f"No item with that key: {key}") from None
        return tuple.__getitem__(self, key)


def _row_factory(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []
    return lambda values: Row(names, values)


_adapters_ready = threading.Lock()
_adapted = False


def _psycopg():
    """psycopg, with the two adapters that keep values as SQLite would give them."""
    global _adapted
    try:
        import psycopg
        from psycopg.adapt import Dumper, Loader
    except ImportError as e:  # pragma: no cover - depends on the install
        raise RuntimeError("a PostgreSQL URL needs psycopg: pip install 'aicefr[services]'") from e
    with _adapters_ready:
        if not _adapted:

            class BoolAsInt(Dumper):
                oid = psycopg.adapters.types["int8"].oid

                def dump(self, obj: bool) -> bytes:
                    return b"1" if obj else b"0"

            class PlainNumber(Loader):
                def load(self, data) -> int | float:
                    d = Decimal(bytes(data).decode())
                    return int(d) if d == d.to_integral_value() else float(d)

            psycopg.adapters.register_dumper(bool, BoolAsInt)
            psycopg.adapters.register_loader("numeric", PlainNumber)
            _adapted = True
    return psycopg


def _connection_args(url: str) -> tuple[str, str]:
    """The server's URL as psycopg takes it, and the schema named by `?schema=` (`public`)."""
    parts = urlsplit(url)
    query = dict(parse_qsl(parts.query))
    schema = query.pop("schema", "public")
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", schema):
        raise ValueError(f"schema name {schema!r}: lower-case letters, digits and _ only")
    return urlunsplit(parts._replace(query=urlencode(query, quote_via=quote))), schema


class PgConnection:
    """A psycopg connection that takes SQLite-dialect statements, as the repositories write them."""

    def __init__(self, raw) -> None:
        self.raw = raw

    def execute(self, sql: str, params: Sequence | None = ()):
        cur = self.raw.cursor()
        has = bool(params)
        cur.execute(to_postgres(sql, has), tuple(params) if has else None)
        return cur

    def executemany(self, sql: str, seq: Iterable[Sequence]):
        cur = self.raw.cursor()
        cur.executemany(to_postgres(sql, True), [tuple(p) for p in seq])
        return cur

    def executescript(self, script: str) -> None:
        for stmt in split_script(script):
            self.raw.execute(ddl_to_postgres(stmt))


_schemas_made: set[tuple[str, str]] = set()

# Idle connections kept per server. Opening a PostgreSQL connection costs a
# round trip and an authentication; every repository method opens one, so a
# page that reads five things would pay that five times. The pool is per
# server, not per schema -- the schema is set each time a connection is taken
# -- and a connection goes back only after a commit or a rollback, so none
# carries a transaction from one method into the next.
POOL_SIZE = 8
_pool: dict[str, list] = {}
_pool_lock = threading.Lock()


def _take(dsn: str):
    with _pool_lock:
        idle = _pool.get(dsn)
        while idle:
            raw = idle.pop()
            if not raw.closed:
                return raw
    return _psycopg().connect(dsn, row_factory=_row_factory)


def _give_back(dsn: str, raw) -> None:
    if raw.closed or raw.info.transaction_status != 0:  # 0 = idle, no transaction open
        raw.close()
        return
    with _pool_lock:
        idle = _pool.setdefault(dsn, [])
        if len(idle) < POOL_SIZE:
            idle.append(raw)
            return
    raw.close()


def _ready(dsn: str, schema: str):
    """A pooled connection on `schema`; a dead one (the server restarted, an idle
    timeout) is dropped and replaced once, so no request fails for it."""
    psycopg = _psycopg()
    raw = _take(dsn)
    try:
        raw.execute(f"SET search_path TO {schema}")
    except psycopg.OperationalError:
        raw.close()
        raw = psycopg.connect(dsn, row_factory=_row_factory)
        raw.execute(f"SET search_path TO {schema}")
    return raw


@contextmanager
def _pg_connect(url: str) -> Iterator[PgConnection]:
    psycopg = _psycopg()
    dsn, schema = _connection_args(url)
    raw = _ready(dsn, schema)
    try:
        if (dsn, schema) not in _schemas_made:
            # Looked up before creating: in a deployment the service's role owns
            # its schema but may not create one, and PostgreSQL checks that right
            # even for CREATE SCHEMA IF NOT EXISTS on a schema that exists.
            found = raw.execute(
                "SELECT 1 FROM pg_namespace WHERE nspname = %s", (schema,)
            ).fetchone()
            if not found:
                try:
                    raw.execute(f"CREATE SCHEMA {schema}")
                except psycopg.errors.DuplicateSchema:
                    raw.rollback()  # another process made it first
            raw.commit()
            _schemas_made.add((dsn, schema))
            raw.execute(f"SET search_path TO {schema}")
        yield PgConnection(raw)
        raw.commit()
    except BaseException:
        if not raw.closed:
            try:
                raw.rollback()
            except psycopg.Error:
                raw.close()  # the original error is the one worth raising
        raise
    finally:
        _give_back(dsn, raw)


# ================================================================= errors


def _errors(name: str) -> tuple[type[Exception], ...]:
    kinds: list[type[Exception]] = [getattr(sqlite3, name)]
    try:
        import psycopg

        kinds.append({"IntegrityError": psycopg.IntegrityError,
                      "OperationalError": psycopg.errors.UndefinedTable}[name])  # fmt: skip
    except ImportError:
        pass
    return tuple(kinds)


# A unique or foreign-key constraint refused the write, in either dialect.
IntegrityError = _errors("IntegrityError")
# The table is not there (a database from before a feature): SQLite raises
# OperationalError, PostgreSQL UndefinedTable.
MissingTable = _errors("OperationalError")


# ================================================================= shared by every repository


def add_columns(c, table: str, wanted: Iterable[tuple[str, str]]) -> None:
    """Add the columns a table created by an older build lacks.

    CREATE TABLE IF NOT EXISTS does nothing for a table that is already there,
    so a machine running an older build would lack the new columns and every
    query naming them would break. Checking the columns and then running ALTER
    TABLE is the minimal upgrade path; a project of this size does not need a
    dedicated migration tool.
    """
    if isinstance(c, PgConnection):
        rows = c.execute(
            "SELECT column_name AS name FROM information_schema.columns"
            " WHERE table_schema = current_schema() AND table_name = ?",
            (table,),
        )
        columns = {r["name"] for r in rows}
        for name, sql_type in wanted:
            if name not in columns:
                # IF NOT EXISTS: two processes starting at once both see it missing.
                column = f"{name} {ddl_to_postgres(sql_type)}"
                c.raw.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column}")
        return
    columns = {r["name"] for r in c.execute(f"PRAGMA table_info({table})")}
    for name, sql_type in wanted:
        if name not in columns:
            c.execute(f"ALTER TABLE {table} ADD COLUMN {name} {sql_type}")


class SqlStore:
    """A repository on one SQLite file or one PostgreSQL schema. Each method opens
    and closes its own connection, so it stays safe under multiple threads."""

    db_path: str

    @property
    def on_postgres(self) -> bool:
        return is_postgres(self.db_path)

    def _prepare_location(self) -> None:
        """A SQLite file's folder exists before the first connection."""
        if not self.on_postgres:
            Path(self.db_path).parent.mkdir(parents=True, exist_ok=True)

    @contextmanager
    def _conn(self) -> Iterator:
        if self.on_postgres:
            with _pg_connect(self.db_path) as c:
                yield c
            return
        # Production settings for SQLite. Defaults are tuned for a single-user
        # desktop file, not for a web server:
        #   timeout      - without it a concurrent writer raises "database is
        #                  locked" immediately instead of waiting its turn.
        #                  Two teachers reviewing at once is enough to hit this.
        #   WAL          - readers no longer block on a writer, so the review
        #                  queue stays responsive while a submission is saved.
        #   foreign_keys - OFF by default in SQLite, which silently allows
        #                  orphan rows in review_action and review_lock.
        conn = sqlite3.connect(self.db_path, timeout=10.0)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL")
        conn.execute("PRAGMA foreign_keys=ON")
        conn.execute("PRAGMA busy_timeout=10000")
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()


# What the repositories' type hints name: a connection and a row of either dialect.
Connection = sqlite3.Connection | PgConnection
DbRow = sqlite3.Row | Row


def table_exists(target: str | Path, table: str) -> bool:
    """Whether `table` is already in the store at `target`, without creating anything.

    For tools that must not run against the wrong store: opening a repository
    creates its tables, so an empty store looks like a valid one with no rows.
    """
    if is_postgres(target):
        with _pg_connect(str(target)) as c:
            row = c.execute("SELECT to_regclass(?) IS NOT NULL", (table,)).fetchone()
            return bool(row[0])
    if not Path(target).is_file():
        return False
    conn = sqlite3.connect(str(target))
    try:
        row = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)
        ).fetchone()
        return row is not None
    finally:
        conn.close()
